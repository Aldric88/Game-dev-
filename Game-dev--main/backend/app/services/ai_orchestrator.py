    def _format_history(self, history: list[dict]) -> str:
        if not history:
            return ""
        lines = ["\nPREVIOUS CONVERSATION HISTORY:"]
        for msg in history:
            role = msg.get("role", "unknown")
            content = msg.get("content", "")
            lines.append(f"{role.upper()}: {content}")
        lines.append("END HISTORY\n")
        return "\n".join(lines)

    async def generate_design(
        self,
        prompt: str,
        history: list[dict] | None = None,
    ) -> OrchestratorResult:
        system = (
            "You are an expert game design architect. Analyze the request and return a "
            "COMPLETE Game Design Document as strict JSON. Do not include markdown formatting "
            "like ```json ... ``` or any text outside the JSON. The JSON must strictly follow "
            'this schema:\n{\n  "summary": "Brief overview of the game",\n'
            '  "game_type": "One of: platformer, shooter, rpg, puzzle, arcade, racing",\n'
            '  "mechanics": ["List of core mechanics"],\n'
            '  "entities": ["List of game entities"],\n'
            '  "win_conditions": ["List of win conditions"],\n'
            '  "technical_requirements": {"framework": "phaser", "width": 800, "height": 600}\n}'
        )
        history_text = self._format_history(history or [])
        full_prompt = f"{system}{history_text}\nCURRENT REQUEST: {prompt}"

        try:
            result = await provider_manager.generate(full_prompt, temperature=0.7)
            design = self._extract_json_object(result.text)
            if not design:
                design = self._fallback_design(prompt)
            summary = design.get("summary", "Generated game design.")
            return OrchestratorResult(summary=summary, payload=design, usage=result.usage)
        except Exception:
            design = self._fallback_design(prompt)
            return OrchestratorResult(
                summary=design["summary"],
                payload=design,
                usage=ProviderUsage(),
            )

