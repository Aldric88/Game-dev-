class AIOrchestrator:
    def _infer_game_type(self, prompt: str) -> str:
        lower = prompt.lower()
        if any(k in lower for k in ("platform", "platformer")):
            return "platformer"
        if any(k in lower for k in ("shoot", "shooter")):
            return "shooter"
        if "racing" in lower:
            return "racing"
        if "puzzle" in lower:
            return "puzzle"
        return "arcade"

    def _infer_entities(self, prompt: str) -> list[str]:
        entities = ["Player"]
        lower = prompt.lower()
        if any(k in lower for k in ("enemy", "enemies", "monster")):
            entities.append("Enemy")
        if any(k in lower for k in ("coin", "collect", "collectible")):
            entities.append("Coin")
        if any(k in lower for k in ("boss", "knight")):
            entities.append("Boss")
        return list(sorted(set(entities)))

    def _extract_json_object(self, text: str) -> dict[str, Any]:
        text = text.strip()
        if text.startswith("```"):
            lines = [l for l in text.splitlines() if not l.startswith("```")]
            text = "\n".join(lines).strip()
        try:
            return json.loads(text)
        except json.JSONDecodeError:
            pass
        start = text.find("{")
        end = text.rfind("}")
        if start != -1 and end != -1:
            try:
                return json.loads(text[start:end + 1])
            except json.JSONDecodeError:
                pass
        return {}

    def _fallback_design(self, prompt: str) -> dict[str, Any]:
        game_type = self._infer_game_type(prompt)
        entities = self._infer_entities(prompt)
        mechanics = ["jump", "gravity", "collect", "collectibles"]
        return {
            "summary": f"Generated {game_type} game using deterministic fallback.",
            "game_type": game_type,
            "mechanics": mechanics,
            "entities": entities,
            "win_conditions": ["Reach target score", "Survive until level complete"],
            "technical_requirements": {"framework": "phaser", "width": 800, "height": 600},
        }

    def _fallback_code(self, prompt: str) -> dict[str, Any]:
        game_type = self._infer_game_type(prompt)
        html = self._self_contained_html_game(game_type)
        return {
            "summary": "Generated starter HTML game using deterministic fallback.",
            "files": {"index.html": html},
            "entry_point": "index.html",
            "dependencies": [],
        }

